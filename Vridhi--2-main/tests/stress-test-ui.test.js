#!/usr/bin/env node
'use strict';
/* Renders the screen in jsdom and checks every function of the simplified layout. Prints SKIP when jsdom is not installed. */
const path = require('path'), fs = require('fs'), assert = require('assert');
let JSDOM; try { ({ JSDOM } = require('jsdom')); } catch (e) { console.log('stress-test-ui: SKIP (jsdom not installed)'); process.exit(0); }
const root = path.join(__dirname, '..');
const dom = new JSDOM('<div id="h"></div>', { runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
for (const f of ['retirement-planner/engine.js', 'stress-test/engine.js', 'stress-test/ui.js']) w.eval(fs.readFileSync(path.join(root, 'modules', f), 'utf8'));
const FH = w.FreedomHorizon;
const inp = Object.assign(FH.defaults(), { age: 48, children: 0, until: 74, corpus: 30000000, roi: 8.05, preOn: '0', houseFund: 14000000, buffer: 1500000, bufferRoi: 6, monthly: 112000, houseInflation: 4, reduceAge: 60, reducePercent: 0, incomeOn: '0', lumpCount: '0' });
let saved = null;
const provider = { clients: () => [{ id: 'a', name: 'Shishir' }], activeId: () => 'a', inputs: () => inp, settings: () => saved, saveSettings: (id, s) => { saved = s; } };
const h = w.document.getElementById('h');
w.StressTestUI.mount(h, provider);
const txt = () => h.textContent;
assert.strictEqual(h.querySelectorAll('.st-tile').length, 5, 'five summary tiles');
assert.ok(txt().includes('14.10 yrs') && txt().includes('11 of 14') && txt().includes('8 of 14'), 'summary values');
assert.strictEqual(h.querySelectorAll('.st-main .st-t tbody tr').length, 14, 'all 14 scenarios');
const row1 = h.querySelector('.st-main .st-t tbody tr');
const cells1 = Array.from(row1.querySelectorAll('td')).map(td => td.textContent);
assert.strictEqual(cells1[0], '1', 'S.No column shows row number');
assert.ok(cells1[1].startsWith('Base Case') && !/^\d+\./.test(cells1[1]), 'Scenario name omits number prefix');
assert.ok(row1.textContent.includes('51.39 yrs') && row1.textContent.includes('Covers plan'), 'base case row');
assert.ok(txt().includes('Falls short') && txt().includes('Never runs out'), 'status labels');
for (const g of ['Monthly expense', 'Survival']) assert.ok(h.querySelector('.st-main .st-t').textContent.includes(g), g + ' column shown');
assert.ok(!txt().includes('What changes') && !txt().includes('Linked to planner') && !txt().includes('Changed by this scenario') && !txt().includes('You can edit'), 'removed group banners and legend clutter');
h.querySelector('[data-st-max]').click();
assert.ok(h.querySelector('.st-scen-card').classList.contains('st-max'), 'Maximize opens full-window table');
h.querySelector('[data-st-max]').click();
assert.ok(!h.querySelector('.st-scen-card').classList.contains('st-max'), 'Restore exits full-window table');
assert.ok(!h.querySelector('.st-main .st-t').textContent.includes('Emergency buffer'), 'Starting position columns hidden by default');
assert.ok(h.querySelector('[data-st-msdb="cols"]').textContent.includes('Default columns'), 'Columns dropdown shows Default columns');
h.querySelector('[data-st-msda="cols:all"]').click();
let ths = Array.from(h.querySelectorAll('.st-main .st-t thead th [data-st-rk]')).map(x => x.textContent.replace(/\s*[▲▼]$/, ''));
assert.strictEqual(ths[0], 'S.No', 'S.No appears first');
assert.strictEqual(ths[1], 'Scenario', 'Scenario appears right after S.No');
assert.ok(ths.indexOf('Emergency buffer') === 3 && ths.includes('Investable') && ths.includes('Net need p.a.'), 'Show all inserts starting position columns right after Scenario');
assert.strictEqual(h.querySelectorAll('.st-main .st-t thead th .rpi').length, 17, 'Every column header includes a calculation tooltip');
h.querySelector('[data-st-msda="cols:reset"]').click();
assert.ok(!h.querySelector('.st-main .st-t').textContent.includes('Emergency buffer'), 'Reset to default hides optional columns');
const bufCol = h.querySelector('[data-st-col="buffer"]'); bufCol.checked = true; bufCol.dispatchEvent(new w.Event('change', { bubbles: true }));
ths = Array.from(h.querySelectorAll('.st-main .st-t thead th [data-st-rk]')).map(x => x.textContent.replace(/\s*[▲▼]$/, ''));
assert.ok(ths.indexOf('Emergency buffer') === 2 && !ths.includes('Corpus'), 'Individual optional column toggle shows only that column');
const rq = h.querySelector('#st-rq'); rq.value = 'Bear Market'; rq.dispatchEvent(new w.Event('input', { bubbles: true }));
assert.strictEqual(h.querySelectorAll('.st-main .st-t tbody tr').length, 1, 'Search filters scenarios live');
rq.value = ''; rq.dispatchEvent(new w.Event('input', { bubbles: true }));
h.querySelector('[data-st-rk="surv"]').click();
assert.ok(h.querySelector('.st-main .st-t tbody tr').textContent.includes('Worst Case'), 'Clicking Survival column header sorts ascending');
assert.strictEqual(h.querySelectorAll('[data-set]').length, 11, 'eleven editable settings');
assert.ok(h.querySelector('[data-st=apply]').disabled, 'Apply waits for a change');
const c1 = h.querySelector('[data-set=conservative]'); c1.value = '5'; c1.dispatchEvent(new w.Event('input', { bubbles: true }));
assert.ok(!h.querySelector('[data-st=apply]').disabled, 'Apply enabled after an edit');
h.querySelector('[data-st=apply]').click();
assert.ok(Math.abs(saved.conservative - 0.05) < 1e-9, 'Apply saves the settings for the client');
const sh = h.querySelector('[data-set=shock]'); assert.ok(sh.value.includes(','), 'shock shown with Indian digit grouping');
h.querySelector('[data-st=reset]').click(); assert.ok(Math.abs(saved.conservative - 0.06) < 1e-9, 'Reset restores defaults');
assert.strictEqual(h.querySelectorAll('.st-d').length, 2, 'engine and notes sections');
assert.strictEqual(h.querySelectorAll('.st-d .st-t tbody tr').length, 70, 'engine table has 70 years');
const f = h.querySelector('[data-st=filter]'); f.value = 'base'; f.dispatchEvent(new w.Event('change', { bubbles: true }));
assert.strictEqual(h.querySelectorAll('.st-d .st-t thead th').length, 6, 'filter shows base case only');
for (const removed of ['Live from Retirement Planner', 'Back to Planner', 'Year-by-Year (base case)', 'Refresh from planner', 'Export CSV']) {
  assert.ok(!txt().includes(removed), removed + ' is removed');
}
/* navigation goes to Retirement Planner > Reports */
w.UI = { tab: 'Goal Planner' }; w.RPUI = { tab: 'status', rv: 'clients' }; let rendered = 0; w.render = () => { rendered++; };
const nav = w.StressTestUI.appProvider();
nav.onYearByYear(); assert.ok(w.RPUI.tab === 'report' && w.RPUI.rv === 'yy' && w.UI.tab === 'Retirement planner' && rendered === 1, 'Year-by-Year link');
nav.onBack(); assert.ok(w.RPUI.tab === 'status' && w.UI.tab === 'Retirement planner', 'Back link');
const css = fs.readFileSync(path.join(root, 'modules', 'stress-test', 'stress-test.css'), 'utf8');
assert.ok(!/#[0-9a-fA-F]{3,6}/.test(css.replace(/var\([^)]*\)/g, '')) || /var\(--card/.test(css), 'colours come from app theme variables');
for (const v of ['--card', '--tx', '--mu', '--bd', '--ac', '--ok', '--er']) assert.ok(css.includes('var(' + v), 'uses theme variable ' + v);
assert.strictEqual(h.querySelectorAll('.st-bnav [data-st-tab]').length, 4, 'four bottom tabs shown');
const appCore = fs.readFileSync(path.join(root, 'modules', 'app-core', 'app.js'), 'utf8');
assert.ok(appCore.includes("m.tab==='Stress Test'") && appCore.includes("UI.tab==='Stress Test'" || appCore.includes("tab==='Stress Test'")), 'Stress Test wired in top Modules dropdown');
const stSrc = fs.readFileSync(path.join(root, 'modules', 'stress-test', 'ui.js'), 'utf8');
assert.ok(stSrc.includes('VRMODULES') && stSrc.includes('tab: "Stress Test"'), 'Stress Test registers as a top-level module');
console.log('stress-test-ui: all checks passed');
